"""
판별 지식베이스 (RAG-lite).
별도 벡터DB 없이, 유형/단계 정의를 프롬프트에 고정 주입하는 방식으로 시작한다.
신종 수법이 발견되면 이 파일에 사례를 추가하는 것만으로 대응 범위를 넓힐 수 있다.
"""

SCAM_TYPES = """
- 기관사칭: 검찰·경찰·금융감독원·국세청 등을 사칭하여 "수사 중", "계좌 연루", "출석 요구" 등으로 압박
- 대출빙자: 저금리 대환대출·정부지원대출을 미끼로 선입금이나 개인정보를 요구
- 가족지인사칭: 자녀·지인을 사칭해 사고·급전 등을 이유로 긴급 송금을 요구
- 투자리딩방: 고수익 투자 정보 제공을 빙자해 리딩방 참여, 앱 설치, 입금을 유도
- 정상: 실제 금융기관·공공기관의 정상적인 안내, 협박·비밀유지·긴급송금 요구가 없음
"""

SCENARIO_STAGES = """
1단계 접촉: 처음 연락, 신뢰를 얻기 위한 도입부 (공식 기관/지인을 사칭하며 대화 시작)
2단계 신뢰구축: 개인정보 일부를 언급하거나 공신력 있는 척하는 자료(가짜 공문 등)를 제시
3단계 고립유도: "가족에게 말하지 말라", "수사 기밀이다", "혼자 처리해야 한다" 등 상담 경로 차단
4단계 정보·앱요구: 원격제어 앱 설치, 계좌 비밀번호, OTP, 신분증 사본 등 요구
5단계 이체·인출: 특정 계좌로 이체 또는 ATM 인출을 즉시 요구, 시간 압박("지금 당장")
"""

def build_reference_block() -> str:
    return f"[사기 유형 정의]\n{SCAM_TYPES}\n[시나리오 단계 정의]\n{SCENARIO_STAGES}"
