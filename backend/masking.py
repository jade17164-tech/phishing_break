"""
개인정보 마스킹 유틸리티
AI 호출 전, 사용자가 입력한 텍스트에서 민감정보를 정규식으로 찾아 치환한다.
"""
import re

# 순서 중요: 더 구체적인 패턴(주민번호, 계좌번호)을 먼저 처리해야
# 전화번호 패턴에 오탐되지 않는다.
PATTERNS = [
    # 주민등록번호: 123456-1234567 또는 1234561234567
    (re.compile(r"(?<!\d)\d{6}[-\s]?[1-4]\d{6}(?!\d)"), "[주민번호마스킹]"),
    # 카드번호: 1234-5678-9012-3456 (4-4-4-4 고정 형태이므로 먼저 검사)
    (re.compile(r"(?<!\d)\d{4}[-\s]\d{4}[-\s]\d{4}[-\s]\d{4}(?!\d)"), "[카드번호마스킹]"),
    # 전화번호: 010-1234-5678, 01012345678, 02-123-4567 등 (0으로 시작하므로 먼저 검사)
    (re.compile(r"(?<!\d)0\d{1,2}[-\s]?\d{3,4}[-\s]?\d{4}(?!\d)"), "[전화번호마스킹]"),
    # 계좌번호로 보이는 나머지 숫자-숫자-숫자 형태 (가장 일반적인 패턴이므로 마지막에 검사)
    (re.compile(r"(?<!\d)\d{2,6}[-\s]\d{2,6}[-\s]\d{2,8}(?!\d)"), "[계좌번호마스킹]"),
]


def mask_pii(text: str) -> str:
    """입력 텍스트에서 개인정보로 추정되는 부분을 마스킹 처리한다."""
    masked = text
    for pattern, replacement in PATTERNS:
        masked = pattern.sub(replacement, masked)
    return masked
